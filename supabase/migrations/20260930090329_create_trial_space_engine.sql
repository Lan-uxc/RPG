create table if not exists public.game_sessions (
  id uuid primary key default gen_random_uuid(),
  session_code text not null unique,
  access_token_hash text not null,
  title text not null default '霧港試煉',
  status text not null default 'active' check (status in ('active','completed','failed','archived')),
  current_scene_key text not null default 'dock',
  turn_no integer not null default 0,
  hp integer not null default 100 check (hp between 0 and 100),
  stamina integer not null default 100 check (stamina between 0 and 100),
  focus integer not null default 70 check (focus between 0 and 100),
  summary text not null default '',
  world_state jsonb not null default '{}'::jsonb,
  flags jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_played_at timestamptz not null default now()
);

create table if not exists public.game_turns (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.game_sessions(id) on delete cascade,
  turn_no integer not null,
  player_input text not null,
  intent text not null,
  resolution jsonb not null default '{}'::jsonb,
  narrative text not null,
  scene_key text not null,
  created_at timestamptz not null default now(),
  unique(session_id, turn_no)
);

create table if not exists public.game_memories (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.game_sessions(id) on delete cascade,
  scope text not null default 'world' check (scope in ('world','player','npc','scene')),
  subject_key text,
  content text not null,
  importance integer not null default 5 check (importance between 1 and 10),
  tags jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.game_npc_states (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.game_sessions(id) on delete cascade,
  npc_key text not null,
  name text not null,
  scene_key text not null,
  disposition integer not null default 50 check (disposition between 0 and 100),
  trust integer not null default 30 check (trust between 0 and 100),
  tension integer not null default 10 check (tension between 0 and 100),
  status text not null default '正常',
  state jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  unique(session_id, npc_key)
);

create table if not exists public.game_inventory (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.game_sessions(id) on delete cascade,
  item_key text not null,
  name text not null,
  quantity integer not null default 1 check (quantity >= 0),
  description text not null default '',
  metadata jsonb not null default '{}'::jsonb,
  unique(session_id, item_key)
);

create index if not exists game_turns_session_created_idx on public.game_turns(session_id, created_at desc);
create index if not exists game_memories_session_importance_idx on public.game_memories(session_id, importance desc, created_at desc);
create index if not exists game_npc_states_session_scene_idx on public.game_npc_states(session_id, scene_key);
create index if not exists game_inventory_session_idx on public.game_inventory(session_id);

alter table public.game_sessions enable row level security;
alter table public.game_turns enable row level security;
alter table public.game_memories enable row level security;
alter table public.game_npc_states enable row level security;
alter table public.game_inventory enable row level security;

