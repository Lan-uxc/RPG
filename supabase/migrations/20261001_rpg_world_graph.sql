-- RPG world graph and durable thread state.
-- Forward-compatible migration for repositories that already have the original game tables.

create table if not exists public.game_scenarios (
  scenario_key text primary key,
  title text not null,
  description text not null default '',
  version integer not null default 1 check (version > 0),
  start_scene_key text not null,
  rules jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.game_places (
  id bigint generated by default as identity primary key,
  scenario_key text not null references public.game_scenarios(scenario_key) on delete cascade,
  scene_key text not null,
  name text not null,
  description text not null default '',
  region_key text,
  tags jsonb not null default '[]'::jsonb,
  state_defaults jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (scenario_key, scene_key)
);

create table if not exists public.game_routes (
  id bigint generated by default as identity primary key,
  scenario_key text not null references public.game_scenarios(scenario_key) on delete cascade,
  from_scene_key text not null,
  to_scene_key text not null,
  label text not null default '',
  travel_minutes integer not null default 5 check (travel_minutes >= 0),
  requirements jsonb not null default '{}'::jsonb,
  effects jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  is_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  unique (scenario_key, from_scene_key, to_scene_key, label)
);

alter table public.game_sessions
  add column if not exists scenario_key text not null default 'normandy_1944';

create table if not exists public.game_threads (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.game_sessions(id) on delete cascade,
  thread_key text not null,
  title text not null,
  status text not null default 'open'
    check (status in ('open','resolved','failed','changed','superseded')),
  pressure integer not null default 0 check (pressure between 0 and 10),
  notes jsonb not null default '[]'::jsonb,
  state jsonb not null default '{}'::jsonb,
  created_turn integer,
  resolved_turn integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(session_id, thread_key)
);

create index if not exists game_threads_session_status_pressure_idx
  on public.game_threads(session_id, status, pressure desc);
create index if not exists game_places_scenario_region_idx
  on public.game_places(scenario_key, region_key);
create index if not exists game_routes_from_idx
  on public.game_routes(scenario_key, from_scene_key);
create index if not exists game_routes_to_idx
  on public.game_routes(scenario_key, to_scene_key);
create index if not exists game_agent_runs_session_idx
  on public.game_agent_runs(session_id);

alter table public.game_scenarios enable row level security;
alter table public.game_places enable row level security;
alter table public.game_routes enable row level security;
alter table public.game_threads enable row level security;

revoke all on public.game_scenarios from anon, authenticated;
revoke all on public.game_places from anon, authenticated;
revoke all on public.game_routes from anon, authenticated;
revoke all on public.game_threads from anon, authenticated;

